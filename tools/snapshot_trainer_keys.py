"""Snapshot the trainer's public configuration without importing torch."""
from dataclasses import fields
from pathlib import Path
import pprint
import sys

APP = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(APP.parent / 'RulzTrainer'))
from rulztrainer import config, __version__  # noqa: E402


def main():
    instance = config.TrainConfig()
    defaults = {f.name: getattr(instance, f.name) for f in fields(instance)}
    keys = {k: type(v).__name__ for k, v in defaults.items()}
    explicit = {'model_arch', 'model_source', 'model_path', 'models_dir', 'transformer_file',
                'text_encoder_file', 'vae_file', 'tokenizer_path', 'attention_backend',
                'gradient_checkpointing', 'checkpoint_keep_blocks', 'block_swap',
                'block_swap_compile', 'activation_offload', 'device', 'multi_gpu',
                'devices', 'dp_balance', 'compile_model', 'cache_dir', 'sample_model_path',
                'sample_model_quant', 'text_encoder_device', 'split_plan', 'parallel_jobs',
                'body_device', 'probe_device'}
    model_keys = tuple(k for k in keys if k in explicit or k.endswith('_quant')
                       or k.startswith(('int8_', 'nvfp4_')))
    values = {'TRAINER_VERSION': __version__, 'KEYS': keys, 'DEFAULTS': defaults,
              'OPTIMIZERS': config.OPTIMIZERS, 'TIMESTEP_SAMPLING': config.TIMESTEP_SAMPLINGS,
              'LR_SCHEDULERS': config.LR_SCHEDULERS, 'ARCH_NAMES': config.ARCH_NAMES,
              'MODEL_PRESETS': config.MODEL_PRESETS, 'MODEL_KEYS': model_keys,
              'ARCH_FULL_SAMPLE': config.ARCH_FULL_SAMPLE, 'ARCH_TURBO': config.ARCH_TURBO,
              'ARCH_TRAINING_ADAPTER': config.ARCH_TRAINING_ADAPTER,
              'ARCH_SAMPLE_DEFAULTS': config.ARCH_SAMPLE_DEFAULTS, 'DATASET_KEYS': config.DATASET_KEYS}
    content = '"""Generated by tools/snapshot_trainer_keys.py; do not edit."""\n\n'
    content += '\n\n'.join(f'{k} = {pprint.pformat(v, sort_dicts=False, width=100)}' for k, v in values.items()) + '\n'
    (APP / 'rulz_optimizer' / 'trainer_keys.py').write_text(content, encoding='utf-8', newline='\n')
    print(f'{len(keys)} keys')


if __name__ == '__main__':
    main()
